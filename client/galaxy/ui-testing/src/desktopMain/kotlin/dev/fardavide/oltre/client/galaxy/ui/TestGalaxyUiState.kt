// **Twenty frames of the Galaxy tab, stated rather than derived — and this file is the one place in
// the repository where that sentence costs three thousand lines.**
//
// Until 0.9.1 every frame here was `state.toGalaxyUiState(...)`, and the header argued for it: the
// galaxy's constants are pinned value by value by `GalaxyBalanceTest` and `GalaxyDistributionTest`,
// so a change that moves these numbers *should* redraw the images — and the first hand-written
// version of this file drifted from the mapper's own formatting within an hour and quietly rendered
// numbers the app would never produce.
//
// The layer split ended that arrangement rather than the argument: `toGalaxyUiState` is a mapping
// from a `GameState`, so it lives in `:client:galaxy:presentation`, and a ui module is a leaf that
// cannot see one. Davide's call, 2026-08-13, taking the split as written and knowing the size.
//
// **What that buys and what it costs, both stated plainly, because the next person to read this
// will want to know whether to undo it.**
//
//   Bought: `:client:galaxy:ui` is a leaf like every other feature's, so the twenty-six baselines
//           and the behaviour suite sit with the composables they exercise, and nothing that draws
//           the galaxy can reach a `GameState` any more.
//   Cost:   the drift the old header warned about is now real again. Nothing recomputes these; a
//           mapper that re-words a verdict or re-rounds a richness leaves this file asserting the
//           old text, and the baselines will agree with it.
//
// **What replaces the compiler is the four unit tests next door** — `GalaxyUiStateTest`,
// `DispatchUiStateTest`, `ProbeActionUiStateTest`, `ReachBandUiStateTest` — which drive the real
// mapper and assert these same sentences. A re-wording still fails; it fails there rather than as a
// changed image. If you are adding a frame here, add it to one of those first and copy the value it
// produced, exactly as this file was made.
//
// **Every value below is the mapper's own output, emitted rather than typed.** The generator walked
// each frame and printed it as Kotlin, so nothing here was transcribed by a human and no baseline
// moved when it landed. `\u00A0` is written out wherever the mapper binds a value to its unit with a
// non-breaking space — invisible in a diff, and the reason a blocked row wraps where it does.
//
// The nine `private val`s at the top are the sub-frames several states share: one ruler and one
// world list serve every home-system frame, so hoisting them is what keeps twenty frames at three
// thousand lines rather than ten. They are numbered rather than named because they are the
// generator's output, and a name would be a claim about them that nothing checks.

